/// 出題1問ぶんの定義。`id` は記録に使うので、一度決めたら変えないこと。
struct Question: Identifiable, Hashable {
    let id: String
    /// 画面に出すひらがな（1文字、または言葉）
    let kana: String
    /// 音声認識が返しそうな別の書き方（「いぬ」→「犬」など）。これと一致しても正解にする。
    var alternatives: [String] = []
}

